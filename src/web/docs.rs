//! Embedded, fully-offline documentation site served under `/docs`.
//!
//! The site is built with `mkdocs build` into `site/` and baked into the binary
//! at compile time via [`rust_embed`], so the running server serves its own help
//! with no filesystem dependency and no external network access. `build.rs`
//! stages that site into `$OUT_DIR/site` — writing a placeholder page there when
//! mkdocs has not run — so a plain `cargo build` works without Python and the
//! source tree is never written to.
//!
//! Each file is tagged with the SHA-256 rust-embed computed at build time, so a
//! browser revalidates with a `304`, and the bytes go out straight from the
//! binary, uncopied.

use std::borrow::Cow;

use axum::extract::{OriginalUri, Path};
use axum::http::{header, HeaderMap, StatusCode};
use axum::response::{IntoResponse, Redirect, Response};
use rust_embed::RustEmbed;

use super::files::if_none_match_hits;

#[derive(RustEmbed)]
#[folder = "$OUT_DIR/site/"]
struct DocSite;

/// `/docs` → redirect to `/docs/` so the site's relative asset/page links
/// resolve correctly (prefix- and proxy-aware via the original request path).
pub async fn docs_root(OriginalUri(uri): OriginalUri) -> Response {
    Redirect::permanent(&format!("{}/", uri.path())).into_response()
}

/// `/docs/` → the documentation home page.
pub async fn docs_index(headers: HeaderMap) -> Response {
    serve("", &headers)
}

/// `/docs/{*path}` → a page or asset within the embedded site.
pub async fn serve_docs(Path(path): Path<String>, headers: HeaderMap) -> Response {
    serve(&path, &headers)
}

/// The documentation site is generated by mkdocs Material, which emits inline
/// bootstrap scripts and styles this crate does not control, so it cannot use
/// the gallery's hash-pinned policy. It still gets a policy that keeps every
/// resource local and forbids framing — and setting it here stops the global
/// middleware from applying the stricter gallery CSP, which would break the
/// site.
const DOCS_CSP: &str = "default-src 'self'; img-src 'self' data:; \
     style-src 'self' 'unsafe-inline'; script-src 'self' 'unsafe-inline'; \
     font-src 'self'; connect-src 'self'; base-uri 'none'; frame-ancestors 'none'";

/// The docs change only with the binary. Not `immutable`, since most names
/// (the pages, the search index) stay the same across an upgrade; a short
/// lifetime plus the content tag keeps an upgraded server's docs current at
/// the price of a `304` now and then.
const DOCS_CACHE_CONTROL: &str = "public, max-age=300";

fn serve(rel: &str, headers: &HeaderMap) -> Response {
    let Some(file) = resolve(rel) else {
        return (StatusCode::NOT_FOUND, "Not found").into_response();
    };
    // Weak, because the response may go out compressed; `If-None-Match`
    // compares weakly anyway.
    let quoted = format!("\"{}\"", hex::encode(file.hash));
    let etag = format!("W/{quoted}");
    if if_none_match_hits(headers, &quoted) {
        return (
            StatusCode::NOT_MODIFIED,
            [
                (header::ETAG, etag.as_str()),
                (header::CACHE_CONTROL, DOCS_CACHE_CONTROL),
            ],
        )
            .into_response();
    }
    (
        [
            (header::CONTENT_TYPE, file.content_type),
            (header::CONTENT_SECURITY_POLICY, DOCS_CSP),
            (header::CACHE_CONTROL, DOCS_CACHE_CONTROL),
            (header::ETAG, etag.as_str()),
        ],
        // Borrowed from the binary (`debug-embed` embeds in debug builds
        // too), so this is no copy.
        file.data,
    )
        .into_response()
}

/// An embedded file, ready to serve.
struct DocFile {
    data: Cow<'static, [u8]>,
    content_type: &'static str,
    /// SHA-256 of `data`, computed at build time.
    hash: [u8; 32],
}

/// Resolve a request path (relative to `/docs/`) to an embedded file, trying the
/// path itself and then its directory index (mkdocs `use_directory_urls`).
fn resolve(rel: &str) -> Option<DocFile> {
    let rel = rel.trim_matches('/');
    let candidates = if rel.is_empty() {
        vec!["index.html".to_string()]
    } else {
        vec![rel.to_string(), format!("{rel}/index.html")]
    };
    for key in candidates {
        if let Some(file) = DocSite::get(&key) {
            return Some(DocFile {
                hash: file.metadata.sha256_hash(),
                data: file.data,
                content_type: content_type_for(&key),
            });
        }
    }
    None
}

/// Map a file extension to a static content type. Covers everything a mkdocs
/// Material site emits; unknown types fall back to `application/octet-stream`.
fn content_type_for(path: &str) -> &'static str {
    let ext = path
        .rsplit('.')
        .next()
        .filter(|_| path.contains('.'))
        .unwrap_or("")
        .to_ascii_lowercase();
    match ext.as_str() {
        "html" | "htm" => "text/html; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "js" | "mjs" => "text/javascript; charset=utf-8",
        "json" | "map" => "application/json",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "jpg" | "jpeg" => "image/jpeg",
        "gif" => "image/gif",
        "webp" => "image/webp",
        "ico" => "image/x-icon",
        "woff" => "font/woff",
        "woff2" => "font/woff2",
        "ttf" => "font/ttf",
        "eot" => "application/vnd.ms-fontobject",
        "txt" => "text/plain; charset=utf-8",
        "xml" => "application/xml",
        _ => "application/octet-stream",
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn content_types_cover_site_assets() {
        assert_eq!(content_type_for("index.html"), "text/html; charset=utf-8");
        assert_eq!(
            content_type_for("assets/main.abc123.css"),
            "text/css; charset=utf-8"
        );
        assert_eq!(
            content_type_for("assets/bundle.def.js"),
            "text/javascript; charset=utf-8"
        );
        assert_eq!(content_type_for("assets/fonts/x.woff2"), "font/woff2");
        assert_eq!(
            content_type_for("search/search_index.json"),
            "application/json"
        );
        assert_eq!(content_type_for("noextension"), "application/octet-stream");
    }

    #[test]
    fn resolve_serves_root_index() {
        // build.rs guarantees at least a placeholder index.html is embedded.
        let file = resolve("").expect("root index present");
        assert!(file.content_type.starts_with("text/html"));
        assert!(!file.data.is_empty());
        assert!(matches!(file.data, Cow::Borrowed(_)));
    }

    #[test]
    fn a_matching_tag_is_answered_with_not_modified() {
        let response = serve("", &HeaderMap::new());
        assert_eq!(response.status(), StatusCode::OK);
        assert_eq!(
            response.headers()[header::CACHE_CONTROL],
            DOCS_CACHE_CONTROL
        );
        let etag = response.headers()[header::ETAG].clone();
        assert!(etag.to_str().unwrap().starts_with("W/\""));

        let mut headers = HeaderMap::new();
        headers.insert(header::IF_NONE_MATCH, etag.clone());
        let response = serve("", &headers);
        assert_eq!(response.status(), StatusCode::NOT_MODIFIED);
        assert_eq!(response.headers()[header::ETAG], etag);

        // The strong form names the same file.
        let strong = etag.to_str().unwrap().trim_start_matches("W/").to_string();
        headers.insert(header::IF_NONE_MATCH, strong.parse().unwrap());
        assert_eq!(serve("", &headers).status(), StatusCode::NOT_MODIFIED);

        headers.insert(header::IF_NONE_MATCH, "\"other\"".parse().unwrap());
        assert_eq!(serve("", &headers).status(), StatusCode::OK);
    }
}
